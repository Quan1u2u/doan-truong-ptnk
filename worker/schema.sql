-- Cơ sở dữ liệu D1 cho Worker. Chạy một lần:
--   npx wrangler d1 execute doan-ptnk --remote --file=worker/schema.sql
CREATE TABLE IF NOT EXISTS kv (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS orders (ma TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (h TEXT PRIMARY KEY, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS hits (k TEXT NOT NULL, t INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS hits_k ON hits(k, t);
CREATE TABLE IF NOT EXISTS hist (id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, who TEXT NOT NULL, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS images (name TEXT PRIMARY KEY, type TEXT NOT NULL, data TEXT NOT NULL);
